def set_font(run, size=10.5, bold=False):
    run.font.name = "Microsoft YaHei"; run._element.rPr.rFonts.set(qn("w:eastAsia"), "Microsoft YaHei"); run.font.size=Pt(size); run.bold=bold
def shade(cell,color):
    x=OxmlElement("w:shd"); x.set(qn("w:fill"),color); cell._tc.get_or_add_tcPr().append(x)
def cell(cell,value,bold=False):
    cell.text=""; p=cell.paragraphs[0]; p.alignment=WD_ALIGN_PARAGRAPH.LEFT; r=p.add_run(str(value)); set_font(r,8.3,bold); cell.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
def p(doc,value,indent=True):
    x=doc.add_paragraph(); x.paragraph_format.line_spacing=1.45; x.paragraph_format.space_after=Pt(4)
    if indent: x.paragraph_format.first_line_indent=Cm(.74)
    set_font(x.add_run(value)); return x
def h(doc,value,level):
    x=doc.add_heading(value,level=level)
    for r in x.runs:set_font(r,15 if level==1 else 12,True)
def table(doc,headers,rows):
    t=doc.add_table(rows=1,cols=len(headers)); t.style="Table Grid"; t.autofit=True
    for i,v in enumerate(headers): cell(t.rows[0].cells[i],v,True); shade(t.rows[0].cells[i],"D9EAF7")
    for row in rows:
      c=t.add_row().cells
      for i,v in enumerate(row):cell(c[i],v)
    doc.add_paragraph(); return t

