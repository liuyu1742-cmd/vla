def replace(p, text):
    props = deepcopy(p.runs[0]._element.rPr) if p.runs and p.runs[0]._element.rPr is not None else None
    p.clear()
    run = p.add_run(text)
    if props is not None: run._element.get_or_add_rPr().append(props)

def put(c, text):
    p = c.paragraphs[0]
    props = deepcopy(p.runs[0]._element.rPr) if p.runs and p.runs[0]._element.rPr is not None else None
    p.clear(); run = p.add_run(str(text))
    if props is not None: run._element.get_or_add_rPr().append(props)
    for extra in c.paragraphs[1:]: extra.clear()

def fill_table(t, header, rows):
    while len(t.rows) < len(rows) + 1:
        t.add_row()
    for i, row in enumerate(t.rows):
        values = header if i == 0 else (rows[i - 1] if i - 1 < len(rows) else [""] * len(header))
        for j, c in enumerate(row.cells): put(c, values[j] if j < len(values) else "")

