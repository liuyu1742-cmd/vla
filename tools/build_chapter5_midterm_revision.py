def font(run, size=10.5, bold=False):
    run.font.name = "Microsoft YaHei"; run._element.rPr.rFonts.set(qn("w:eastAsia"), "Microsoft YaHei"); run.font.size = Pt(size); run.bold = bold

def shade(cell, color):
    tc_pr = cell._tc.get_or_add_tcPr(); shd = OxmlElement("w:shd"); shd.set(qn("w:fill"), color); tc_pr.append(shd)

def text(cell, value, bold=False):
    cell.text = ""; r = cell.paragraphs[0].add_run(str(value)); font(r, 8.5, bold)

def para(doc, value, indent=True):
    p=doc.add_paragraph(); p.paragraph_format.line_spacing=1.5; p.paragraph_format.space_after=Pt(4)
    if indent: p.paragraph_format.first_line_indent=Cm(0.74)
    font(p.add_run(value)); return p

def heading(doc, value, level):
    p=doc.add_heading(value, level=level)
    for r in p.runs: font(r, 15 if level==1 else 12, True)
    return p

def table(doc, headers, rows):
    t=doc.add_table(rows=1, cols=len(headers)); t.style="Table Grid"
    for i,h in enumerate(headers): text(t.rows[0].cells[i],h,True); shade(t.rows[0].cells[i],"D9EAF7")
    for row in rows:
        cells=t.add_row().cells
        for i,v in enumerate(row): text(cells[i],v)
    doc.add_paragraph(); return t

